"""The benchmark scoreboard (MF-047, §7A.13), generated from the registry and run manifests.

    python -m benchmarks.scoreboard --write    # research/results/BENCHMARK_SCOREBOARD.md

One row per suite: its source, the vendor's number kept as theirs, our result
only if a manifest records a run, and the claim level that result reaches
(L0 implementation ... L4 independent confirmation). A suite with no run says
NOT_RUN and why; nothing is filled in.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from benchmarks.manifest import read_all
from benchmarks.registry import load, notes

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "research" / "results" / "BENCHMARK_SCOREBOARD.md"


def claim_level(m: dict[str, Any] | None) -> str:
    if m is None:
        return "—"
    v = m.get("verification", {})
    if v.get("independent_replicated"):
        return "L4"
    if m.get("decision") in ("PASS", "FAIL", "INCONCLUSIVE") and v.get("baseline_registered") and m.get("prereg"):
        return "L2" if v.get("holdout_frozen") else "L1"
    return "L1" if m.get("decision") == "DESCRIPTIVE" else "L0"


def vendor(s: dict[str, Any]) -> str:
    vr = s.get("vendor_reported")
    if not vr:
        return "—"
    arms = vr.get("arms", {})
    parts = []
    for name, a in arms.items():
        score = a.get("rubric_pct", a.get("pct"))
        solved = a.get("solved")
        parts.append(f"{name}: " + (f"{score}%" if score is not None else f"{solved} solved"))
    return "; ".join(parts) + f" ([source]({vr['source']}))"


def render() -> str:
    reg = load()
    runs = {m["suite"]: m for m in read_all()}
    lines = ["# Benchmark scoreboard", "",
             "Generated by `python -m benchmarks.scoreboard --write` from `benchmarks/registry.json` and "
             "`research/results/bench_runs/`. Vendor numbers are theirs, on their harness and model; they are "
             "never Memory Fabric results. NOT_RUN is not a result.", "",
             "| suite | name | vendor-reported (theirs) | Memory Fabric | decision | claim level |",
             "|---|---|---|---|---|---|"]
    for s in reg["suites"]:
        m = runs.get(s["id"])
        if m:
            ours = f"run `{m['run_id']}` at `{m['repo_commit']}`"
            decision = m["decision"]
        elif s["run_status"] == "RUN":
            ours = ", ".join(f"[{Path(r).name or r}]({'../../' + r})" for r in s.get("results", [])) or "see registry"
            decision = "recorded elsewhere"
        else:
            ours = f"not run: {s['reason']}"
            decision = s["run_status"]
        lines.append(f"| {s['id']} | {s['name']} | {vendor(s)} | {ours} | {decision} | {claim_level(m)} |")
    found = notes(reg)
    lines += ["", "## Arithmetic notes on vendor tables", "",
              *([f"- {n}" for n in found] or ["- none"]), ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

"""The sqlite3 connection interface, over a psycopg connection.

`ContentVault`, `Outbox`, `SqliteRevocations` and a handful of read paths take
the event log's connection and run SQL on it, and they share it on purpose: a
retraction's event, its quarantine and its outbox rows commit in **one**
transaction or not at all (invariant 3, and `txn.py` for the bug that taught
it). Porting each of them to a second SQL dialect would fork every query in
the governance path. Giving them a connection that accepts their SQL keeps one
copy of each query, and keeps the shared transaction, which is the property
that matters.

## What is translated, exhaustively

| SQLite | PostgreSQL |
|---|---|
| `?` placeholder | `%s` (and a literal `%` doubled, as psycopg requires) |
| `INSERT OR IGNORE INTO ...` | `INSERT INTO ... ON CONFLICT DO NOTHING` |
| `INTEGER PRIMARY KEY AUTOINCREMENT` | `BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY` |
| `INTEGER` in DDL | `BIGINT` -- every timestamp here is in milliseconds, which overflows Postgres's 32-bit `integer` in 1970 + 24 days |
| `BLOB` in DDL | `BYTEA` |

`ON CONFLICT (...) DO UPDATE SET x = excluded.x` needs nothing: it is the same
syntax in both.

## What is refused

`PRAGMA`, `sqlite_master`, `INSERT OR REPLACE`, `executescript` with
parameters, and `cursor.lastrowid` raise `UnsupportedOnPostgres` rather than
being approximated. A translation that guessed would fail somewhere less
obvious -- `INSERT OR REPLACE` is a delete-then-insert in SQLite and an upsert
would not fire the same triggers -- so the adapter's contract is: the SQL in
this repository either runs with the same meaning, or fails at the call site
naming the construct. Callers that need a SQLite-only path (the 0.4.0
`target_key` migration, which no Postgres store can need) check
`dialect(conn)` and skip it.
"""

from __future__ import annotations

import re
from contextlib import contextmanager
from typing import Any, Callable, Iterator, Sequence


class UnsupportedOnPostgres(RuntimeError):
    """SQL that has no faithful Postgres translation."""


def dialect(conn: Any) -> str:
    """`"postgres"` for this adapter, `"sqlite"` for anything else."""
    return getattr(conn, "dialect", "sqlite")


class Row(tuple):
    """Indexable by position and by column name, like `sqlite3.Row`."""

    _names: tuple[str, ...] = ()

    def __new__(cls, values: Sequence[Any], names: tuple[str, ...]) -> "Row":
        row = super().__new__(cls, values)
        row._names = names
        return row

    def __getitem__(self, key: Any) -> Any:  # type: ignore[override]
        if isinstance(key, str):
            try:
                return tuple.__getitem__(self, self._names.index(key))
            except ValueError:
                raise IndexError(f"no such column: {key}") from None
        return tuple.__getitem__(self, key)

    def keys(self) -> list[str]:
        return list(self._names)


def _row_factory(cursor: Any) -> Callable[[Sequence[Any]], Row]:
    names = tuple(d.name for d in (cursor.description or ()))
    return lambda values: Row(values, names)


_REFUSED = (
    (re.compile(r"^\s*PRAGMA\b", re.I), "PRAGMA"),
    (re.compile(r"\bsqlite_master\b", re.I), "sqlite_master"),
    (re.compile(r"\bINSERT\s+OR\s+REPLACE\b", re.I), "INSERT OR REPLACE"),
)
_OR_IGNORE = re.compile(r"\bINSERT\s+OR\s+IGNORE\s+INTO\b", re.I)
_AUTOINCREMENT = re.compile(r"\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b", re.I)
_INTEGER = re.compile(r"\bINTEGER\b", re.I)
_BLOB = re.compile(r"\bBLOB\b", re.I)


def translate(sql: str, *, parameters: bool) -> str:
    """One SQLite statement in this repository's dialect, as Postgres.

    `parameters` says whether the statement will be executed with bound
    values: only then does psycopg treat `%` as a placeholder marker, so only
    then must a literal one be doubled.
    """
    for pattern, name in _REFUSED:
        if pattern.search(sql):
            raise UnsupportedOnPostgres(
                f"{name} has no faithful Postgres translation: {sql.strip()[:80]}")
    ignore = bool(_OR_IGNORE.search(sql))
    if ignore:
        if re.search(r"\bON\s+CONFLICT\b", sql, re.I):
            raise UnsupportedOnPostgres(
                "INSERT OR IGNORE with its own ON CONFLICT clause")
        sql = _OR_IGNORE.sub("INSERT INTO", sql)
    out: list[str] = []
    quote: str | None = None
    for ch in sql:
        if quote:
            if ch == quote:
                quote = None
            if ch == "%" and parameters:
                out.append("%%")
            else:
                out.append(ch)
            continue
        if ch in ("'", '"'):
            quote = ch
            out.append(ch)
        elif ch == "?":
            out.append("%s")
        elif ch == "%" and parameters:
            out.append("%%")
        else:
            out.append(ch)
    sql = "".join(out)
    if re.match(r"\s*(CREATE|ALTER)\b", sql, re.I):
        sql = _ddl(sql)
    if ignore:
        sql = sql.rstrip().rstrip(";") + " ON CONFLICT DO NOTHING"
    return sql


def _ddl(sql: str) -> str:
    sql = _AUTOINCREMENT.sub(
        "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sql)
    sql = _INTEGER.sub("BIGINT", sql)
    return _BLOB.sub("BYTEA", sql)


def _statements(script: str) -> list[str]:
    """Split a DDL script on `;`, dropping `--` comments.

    The scripts this is used on are this repository's own schemas: no string
    literal in them contains a semicolon, which a test pins.
    """
    lines = [line.split("--", 1)[0] for line in script.splitlines()]
    return [s.strip() for s in "\n".join(lines).split(";") if s.strip()]


class PgCursor:
    def __init__(self, cursor: Any) -> None:
        self._cursor = cursor

    def fetchone(self) -> Row | None:
        if self._cursor.description is None:
            return None
        return self._cursor.fetchone()

    def fetchall(self) -> list[Row]:
        if self._cursor.description is None:
            return []
        return self._cursor.fetchall()

    def __iter__(self) -> Iterator[Row]:
        return iter(self.fetchall())

    @property
    def rowcount(self) -> int:
        return self._cursor.rowcount

    @property
    def lastrowid(self) -> int:
        raise UnsupportedOnPostgres(
            "lastrowid: Postgres has no implicit rowid; use RETURNING")


class PgConnection:
    """What the governance modules see in place of a `sqlite3.Connection`.

    Transactions are the owning log's, so a vault write inside
    `log.transaction()` is part of the same Postgres transaction as the event
    appended beside it -- the reason this adapter exists rather than each
    module opening its own connection.
    """

    dialect = "postgres"

    def __init__(self, raw: Any, transaction: Callable[[], Any],
                 depth: Callable[[], int]) -> None:
        self.raw = raw
        self._transaction = transaction
        self._depth = depth

    def execute(self, sql: str, parameters: Sequence[Any] = ()) -> PgCursor:
        params = tuple(parameters) if parameters else None
        cursor = self.raw.cursor(row_factory=_row_factory)
        cursor.execute(translate(sql, parameters=params is not None), params)
        return PgCursor(cursor)

    def executescript(self, script: str) -> None:
        # One transaction for the script, like sqlite3's executescript, and
        # nested inside the caller's when there is one.
        with self.transaction():
            for statement in _statements(script):
                self.raw.execute(translate(statement, parameters=False))

    @contextmanager
    def transaction(self) -> Iterator[None]:
        with self._transaction():
            yield

    @property
    def depth(self) -> int:
        return self._depth()

    def backup(self, *_: Any, **__: Any) -> None:
        raise UnsupportedOnPostgres(
            "backup: use pg_dump, which is consistent under concurrent writers; "
            "a file copy of the kind SQLite's backup API makes has no "
            "Postgres equivalent")

"""The SQLite-to-Postgres translation, without a database.

What runs on Postgres is tested by running the whole suite through
`tests/pg_backend.py`. This pins the translation rules themselves, so a change
to one is caught in the zero-dependency CI run that has no Postgres.
"""

from __future__ import annotations

import unittest

from memory_fabric.governance import erasure
from memory_fabric import identity, outbox
from memory_fabric.storage.pgcompat import (
    Row,
    UnsupportedOnPostgres,
    _statements,
    translate,
)


class TranslateTest(unittest.TestCase):
    def test_placeholders(self) -> None:
        self.assertEqual(
            translate("SELECT 1 FROM t WHERE a = ? AND b = ?", parameters=True),
            "SELECT 1 FROM t WHERE a = %s AND b = %s")

    def test_question_mark_in_a_literal_is_kept(self) -> None:
        self.assertEqual(
            translate("SELECT '?' FROM t WHERE a = ?", parameters=True),
            "SELECT '?' FROM t WHERE a = %s")

    def test_percent_is_doubled_only_with_parameters(self) -> None:
        self.assertEqual(
            translate("SELECT * FROM t WHERE a LIKE 'x%' AND b = ?",
                      parameters=True),
            "SELECT * FROM t WHERE a LIKE 'x%%' AND b = %s")
        self.assertEqual(
            translate("SELECT * FROM t WHERE a LIKE 'x%'", parameters=False),
            "SELECT * FROM t WHERE a LIKE 'x%'")

    def test_insert_or_ignore(self) -> None:
        self.assertEqual(
            translate("INSERT OR IGNORE INTO t (a) VALUES (?)", parameters=True),
            "INSERT INTO t (a) VALUES (%s) ON CONFLICT DO NOTHING")

    def test_upsert_is_unchanged(self) -> None:
        sql = ("INSERT INTO k (id, m) VALUES (?, ?) "
               "ON CONFLICT(id) DO UPDATE SET m = excluded.m")
        self.assertEqual(translate(sql, parameters=True),
                         sql.replace("?", "%s"))

    def test_ddl_types(self) -> None:
        out = translate(
            "CREATE TABLE IF NOT EXISTS t (id INTEGER PRIMARY KEY AUTOINCREMENT, "
            "n INTEGER NOT NULL, k BLOB)", parameters=False)
        self.assertIn("BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", out)
        self.assertIn("n BIGINT NOT NULL", out)
        self.assertIn("k BYTEA", out)

    def test_integer_outside_ddl_is_left_alone(self) -> None:
        sql = "SELECT CAST(a AS INTEGER) FROM t"
        self.assertEqual(translate(sql, parameters=False), sql)

    def test_refusals(self) -> None:
        for sql in ("PRAGMA table_info(t)",
                    "SELECT name FROM sqlite_master",
                    "INSERT OR REPLACE INTO t VALUES (?)",
                    "INSERT OR IGNORE INTO t VALUES (?) ON CONFLICT DO NOTHING"):
            with self.subTest(sql=sql), self.assertRaises(UnsupportedOnPostgres):
                translate(sql, parameters=True)


class SchemaTest(unittest.TestCase):
    """Every schema the adapter runs splits cleanly and translates."""

    SCHEMAS = {
        "outbox": outbox._SCHEMA,
        "content_keys": erasure._SCHEMA,
        "revocations": identity.SqliteRevocations._SCHEMA,
    }

    def test_no_literal_holds_a_semicolon(self) -> None:
        # `_statements` splits on `;`, which is only sound if no string
        # literal in the scripts it is used on contains one.
        # A literal cut by the split leaves a piece with an odd quote count.
        for name, script in self.SCHEMAS.items():
            for statement in _statements(script):
                with self.subTest(schema=name, statement=statement[:40]):
                    self.assertEqual(statement.count("'") % 2, 0)
                    translate(statement, parameters=False)

    def test_every_timestamp_column_is_64_bit(self) -> None:
        for name, script in self.SCHEMAS.items():
            for statement in _statements(script):
                out = translate(statement, parameters=False)
                with self.subTest(schema=name):
                    self.assertNotRegex(out, r"\bINTEGER\b")


class RowTest(unittest.TestCase):
    def test_like_sqlite_row(self) -> None:
        row = Row((1, "x"), ("seq", "name"))
        self.assertEqual(row[0], 1)
        self.assertEqual(row["name"], "x")
        self.assertEqual(dict(zip(row.keys(), row)), {"seq": 1, "name": "x"})
        self.assertEqual(tuple(row), (1, "x"))
        with self.assertRaises(IndexError):
            row["missing"]


if __name__ == "__main__":  # pragma: no cover
    unittest.main()

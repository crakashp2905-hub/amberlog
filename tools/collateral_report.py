"""One report of collateral damage: what each safety mechanism holds or blocks that it should not (GOV-18).

    python tools/collateral_report.py --write    # research/results/collateral-damage.md

Every attack-recall number in this repository has a false-positive number next
to it somewhere; this puts them on one page, read from the recorded results
(never retyped), with the commit each came from and a 95% upper bound where a
rate is zero (`benchmarks.stats.zero_events_upper`): seeing 0 in n does not
mean the rate is 0.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
RESULTS = ROOT / "research" / "results"
OUT = RESULTS / "collateral-damage.md"


def _load(name: str) -> Any:
    return json.loads((RESULTS / f"{name}.json").read_text(encoding="utf-8"))


def rows() -> list[dict[str, Any]]:
    from benchmarks.stats import wilson, zero_events_upper

    def rate(k: int, n: int) -> str:
        if n == 0:
            return "—"
        if k == 0:
            return f"0 / {n} (≤ {100 * zero_events_upper(n):.2f}% at 95%)"
        lo, hi = wilson(k, n)
        return f"{k} / {n} = {100 * k / n:.2f}% [{100 * lo:.2f}, {100 * hi:.2f}]"

    out = []
    s1 = _load("s1-screen-false-positives")
    t = s1["head"]["lme"]["test"]
    out.append({"mechanism": "write-time injection screen (default)", "benign": "LongMemEval conversation turns",
                "held": rate(t["injection"], t["turns"]), "commit": s1["commit"], "source": "s1-screen-false-positives"})
    d = s1["head"]["deepset_test"]
    out.append({"mechanism": "write-time injection screen (default)", "benign": "deepset benign prompts",
                "held": rate(d["benign_flagged"], d["benign"]), "commit": s1["commit"], "source": "s1-screen-false-positives"})
    s1b = _load("s1b-model-screen")
    c = s1b["rows"]["text+sonnet"]["conversation"]
    out.append({"mechanism": "model screen, opt-in (Sonnet)", "benign": "conversation turns",
                "held": rate(c["benign_flagged"], c["benign"]), "commit": s1b["commit"], "source": "s1b-model-screen"})
    o1 = _load("o1-typed-claims")
    out.append({"mechanism": "typed claim check (default in personal/team)", "benign": "non-contradicting claims, held-out world",
                "held": f"{o1['verdict']['typed_false_holds']:.3f} of non-contradictions", "commit": o1["commit"],
                "source": "o1-typed-claims"})
    c3 = _load("c3-free-text")
    for m in ("haiku", "sonnet"):
        out.append({"mechanism": f"model claim check, opt-in ({m})", "benign": "non-contradicting claims",
                    "held": f"{c3['verdict'][m]['false_holds']:.3f} of non-contradictions", "commit": c3["commit"],
                    "source": "c3-free-text"})
    s2 = _load("s2-launder-sim")
    for arm in ("provenance", "exposure"):
        a = s2["arms"][arm]
        out.append({"mechanism": f"independence check `{arm}`" + (" (opt-in strict)" if arm == "exposure" else ""),
                    "benign": "genuinely independent corroborations", "held": f"{a['blocked_independent']:.3f} blocked",
                    "commit": s2["commit"], "source": "s2-launder-sim"})
    return out


def render() -> str:
    lines = ["# Collateral damage — what the safety mechanisms hold that they should not", "",
             "Generated by `tools/collateral_report.py` from the recorded results; each row links its source. "
             "Attack recall for the same mechanisms is in those sources. A zero is reported with its 95% "
             "upper bound, because 0 in n is not a rate of 0.", "",
             "| mechanism | benign population | held or blocked | commit | source |", "|---|---|---|---|---|"]
    for r in rows():
        lines.append(f"| {r['mechanism']} | {r['benign']} | {r['held']} | `{r['commit']}` | "
                     f"[{r['source']}]({r['source']}.md) |")
    lines += ["", "Reading: the default screens hold well under 0.1% of ordinary conversation; the opt-in "
              "strict independence check blocks a quarter of genuinely independent corroborations, which is why "
              "it is opt-in.", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--write" in argv:
        OUT.write_text(text, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))

"""Render a release evidence bundle as one page: what was checked, on which commit, with what result.

    python tools/release_report.py dist/release-evidence/<sha>     # prints the page

`tools/release_bundle.py` writes the page into the bundle as
`RELEASE_REPORT.md`; CI uploads the bundle for every commit on main. The
page is generated, never edited: every number on it comes from a file in
the same bundle, and the manifest pins those files by sha256. A number
quoted in a release note should be copied from the report for the tagged
commit, not measured again by hand.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path
from typing import Any


def _load(path: Path) -> Any:
    return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None


def _mark(ok: bool) -> str:
    return "pass" if ok else "**FAIL**"


def render(bundle: Path) -> str:
    manifest = _load(bundle / "manifest.json") or {}
    lines = [f"# Release report: `{manifest.get('commit', '?')[:12]}`", "",
             f"Package {manifest.get('package_version')}, schema "
             f"{manifest.get('schema_version')}, Python {manifest.get('python')} on "
             f"{manifest.get('platform')}, built {manifest.get('built_at')}"
             + (" — **dirty tree, rehearsal only**" if manifest.get("dirty") else "") + ".",
             "", "Generated by `tools/release_report.py` from this bundle; do not edit.", "",
             "## Checks", "", "| check | result |", "|---|---|"]
    lines += [f"| {name} | {_mark(ok)} |" for name, ok in manifest.get("checks", {}).items()]

    tests = _load(bundle / "tests.json")
    if tests and not tests.get("skipped_here"):
        lines += ["", f"Unit suite: **{tests['run']}** run, {tests['skipped']} skipped, "
                      f"{len(tests['failures'])} failures, {len(tests['errors'])} errors."]
    elif tests:
        lines += ["", "Unit suite: run by CI on this commit, not repeated in the bundle."]

    gate = _load(bundle / "adversarial-gate.json")
    if gate:
        lines += ["", "## Adversarial gate", "", "| family | tests | result |", "|---|---|---|"]
        lines += [f"| {name.replace('_', ' ')} | {fam['tests']} | {_mark(fam['passed'])} |"
                  for name, fam in gate["families"].items()]

    bench = _load(bundle / "product-bench.json")
    if bench:
        lines += ["", "## Product benchmark", "",
                  f"`experiments.product_bench`, seed {bench['seed']}"
                  + (", quick sizes" if bench.get("quick") else "")
                  + ". One process, SQLite on local disk; an operational measurement "
                    "with no threshold.", "",
                  "| memories | recall@1 | recall@5 | MRR | remember p50 / p95 ms | "
                  "retrieve p50 / p95 ms | writes/s | reads/s | disk B/mem | heap B/mem | "
                  "false blocks |", "|" + "---|" * 11]
        for p in bench["points"]:
            q, lat, tp, g, fb = (p["quality"], p["latency_ms"], p["throughput_per_s"],
                                 p["growth"], p["false_blocks"])
            lines.append(
                f"| {p['memories']:,} | {q['recall_at_1']} | {q['recall_at_5']} | {q['mrr']} | "
                f"{lat['remember']['p50']} / {lat['remember']['p95']} | "
                f"{lat['retrieve']['p50']} / {lat['retrieve']['p95']} | "
                f"{tp['remember']} | {tp['retrieve']} | {g['disk_bytes_per_memory']} | "
                f"{g['heap_bytes_per_memory']} | {fb['blocked']}/{fb['benign_writes']} |")

    wheels = bundle / "wheel.sha256"
    if wheels.exists():
        lines += ["", "## Wheels", "", "```", wheels.read_text(encoding="utf-8").strip(), "```"]
    lines += ["", "## Files", "", "| file | sha256 |", "|---|---|"]
    lines += [f"| {name} | `{digest[:16]}…` |" for name, digest in manifest.get("files", {}).items()]
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    sys.stdout.write(render(Path(sys.argv[1])))
